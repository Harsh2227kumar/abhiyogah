"""Plain-language explanation of a stored decision record.

Explanations are rendered from the record alone, never regenerated by re-running the engine or an
LLM, so what an auditor reads is exactly what was decided and hashed. Every line comes from a field
of the record; nothing is inferred.
"""

from pydantic import JsonValue

from abhiyogah.domain.decision import DecisionRecord
from abhiyogah.domain.money import Paise, format_inr

__all__ = ["render_explanation"]


def _value(v: JsonValue) -> str:
    """A compact rendering of a JSON value."""
    if isinstance(v, list):
        return "[" + ", ".join(_value(x) for x in v) + "]"
    return str(v)


def render_explanation(record: DecisionRecord) -> list[str]:
    """One line per fact of the decision, in a fixed order."""
    lines = [
        f"Obligation {record.obligation_id}, clause {record.clause}, on complaint "
        f"{record.complaint_id}, evaluated as of {record.as_of.isoformat()}.",
        f"Result: {record.result.value}.",
    ]
    if record.anchor_date is not None:
        lines.append(f"Rule parameters were taken as in force on {record.anchor_date}.")
    for p in record.parameters:
        lines.append(
            f"Parameter {p.name} = {_value(p.value)} (effective {p.effective_date}, "
            f"{p.reference}, {p.verification.value})."
        )
    for f in record.input_facts:
        who = f.provenance.actor or f.provenance.model or f.provenance.source.value
        src = f" from event {f.event_id}" if f.event_id else ""
        lines.append(
            f"Fact {f.name} = {_value(f.value)}{src} ({f.provenance.source.value}: {who})."
        )
    for i, check in enumerate(record.condition_trace, start=1):
        mark = "yes" if check.result else "no"
        detail = f" ({check.detail})" if check.detail else ""
        lines.append(f"Check {i}: {check.condition}: {mark}{detail}.")
    if record.deadline is not None:
        d = record.deadline
        start = f" from {d.start_date}" if d.start_date else ""
        days = f", {d.duration_days} {d.basis.value.lower()} days" if d.duration_days else ""
        stop = d.stop_event.value if d.stop_event else "none"
        lines.append(
            f"Deadline {d.due_date}: clock {d.start_event.value}{start}{days} "
            f"(basis {d.basis_status.value.lower()}), stopped by {stop}. {d.rule}".rstrip()
        )
    if record.calendar_version:
        lines.append(f"Calendar version {record.calendar_version}.")
    if record.breach is not None:
        b = record.breach
        when = f", stopped {b.stop_date}" if b.stop_date else ""
        lines.append(f"Breach: due {b.due_date}{when}, {b.days_late} day(s) late.")
    if record.compensation is not None:
        comp = record.compensation
        lines.append(
            f"Compensation {format_inr(Paise(comp.amount_paise))} = {comp.formula}"
            + (f" with {comp.inputs}" if comp.inputs else "")
            + "."
        )
    for a in record.required_actions:
        due = f" by {a.due_date}" if a.due_date else ""
        reason = f" ({a.reason})" if a.reason else ""
        lines.append(f"Required action: {a.action}{due}{reason}.")
    lines.append(f"Record hash {record.hash or 'unsealed'}, chained after {record.prev_hash}.")
    return lines
